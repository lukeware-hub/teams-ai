import type { Spec } from '../contracts/spec.js';
import { renderSpecMd } from '../refine/spec-md.js';

/** The spec.md of a documentation-repository spec folder: a banner that names no machine file, then the spec. */
export function renderRepoSpec(spec: Spec): string {
  return `> Generated by teams-ai from the refinement. Do not edit.\n\n${renderSpecMd(spec)}`;
}
