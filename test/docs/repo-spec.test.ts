import { describe, expect, it } from 'vitest';
import type { Spec } from '../../server/contracts/spec.js';
import { renderRepoSpec } from '../../server/docs/repo-spec.js';
import { renderSpecMd } from '../../server/refine/spec-md.js';

const spec = {
  specId: 'todo-001',
  specVersion: 1,
  specHash: null,
  type: 'bug',
  bug: { actual: '500', expected: '200', reproduction: 'GET /todos' },
  objectives: ['Listar tarefas'],
  features: [],
  acceptanceCriteria: [{ id: 'AC-1', given: 'uma lista', when: 'abrir', then: 'ver os itens', smoke: false }],
  outOfScope: [],
  externalDependencies: [{ name: 'Postgres', purpose: 'dados', secretNames: ['DB_URL'] }],
  tasks: [{ title: 'Rota', description: 'Criar GET /todos' }],
  status: 'refining',
  validationReports: [],
} as Spec;

const BANNER = '> Generated by teams-ai from the refinement. Do not edit.';

describe('renderRepoSpec', () => {
  it('opens with a banner that names no machine file', () => {
    expect(renderRepoSpec(spec).split('\n')[0]).toBe(BANNER);
    expect(renderRepoSpec(spec)).not.toContain('spec.json');
  });

  it('keeps the body of renderSpecMd after the banner', () => {
    expect(renderRepoSpec(spec)).toBe(`${BANNER}\n\n${renderSpecMd(spec)}`);
  });
});
