import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { Workspace } from '../../server/orchestrator/workspace.js';
import { draftPaths, type Draft } from '../../server/refine/draft.js';
import { projectDraftFiles } from '../../server/refine/docs-projection.js';
import { makeSpec } from '../fixtures/contracts.js';

const ALIAS = 'hello-app-login';
let root = '';
let draft: Draft;

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'docs-projection-'));
  draft = draftPaths({ projectId: 'hello-app', root } as Workspace, 'hello-app-001');
  for (const doc of ['project.md', 'flow.md', 'briefing.md', 'design.md', 'stack.md']) {
    await fs.mkdir(draft.docs, { recursive: true });
    await fs.writeFile(path.join(draft.docs, doc), `# ${doc}\n`);
  }
});

afterEach(async () => {
  await fs.rm(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
});

/** Writes one alias folder of the draft: its spec.json, and whichever of the other files the test names. */
async function writeAlias(alias: string, files: Record<string, string>): Promise<void> {
  const dir = path.join(draft.docs, 'specs', alias);
  await fs.mkdir(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) await fs.writeFile(path.join(dir, name), text);
}

describe('projectDraftFiles', () => {
  it('projects a monolith spec to docs/specify/<alias>, with the five documents at docs/', async () => {
    await writeAlias(ALIAS, {
      'spec.json': JSON.stringify(makeSpec({ specId: ALIAS, repository: 'hello-app' })),
      'implementation-plan.md': '# plan\n',
      'task.md': '# task\n',
    });
    const files = await projectDraftFiles(draft, 'monolith', [{ alias: ALIAS }]);
    expect(Object.keys(files).sort()).toEqual([
      'docs/briefing.md',
      'docs/design.md',
      'docs/flow.md',
      'docs/project.md',
      `docs/specify/${ALIAS}/plan.md`,
      `docs/specify/${ALIAS}/spec.md`,
      `docs/specify/${ALIAS}/task.md`,
      'docs/stack.md',
    ]);
    expect(files[`docs/specify/${ALIAS}/plan.md`]).toBe('# plan\n');
    expect(files[`docs/specify/${ALIAS}/task.md`]).toBe('# task\n');
    expect(files[`docs/specify/${ALIAS}/spec.md`]).toMatch(/^> Generated by teams-ai from the refinement\. Do not edit\./);
  });

  it('projects a microservice spec under its repository folder', async () => {
    await writeAlias(ALIAS, {
      'spec.json': JSON.stringify(makeSpec({ specId: ALIAS, repository: 'hello-api' })),
      'implementation-plan.md': '# plan\n',
    });
    const files = await projectDraftFiles(draft, 'microservices', [{ alias: ALIAS, service: 'hello-api' }]);
    expect(files[`docs/hello-api/specify/${ALIAS}/spec.md`]).toBeDefined();
    expect(files[`docs/hello-api/specify/${ALIAS}/plan.md`]).toBe('# plan\n');
    expect(files[`docs/hello-api/specify/${ALIAS}/task.md`]).toBeUndefined();
  });

  it('never projects spec.json or preplan.json', async () => {
    await writeAlias(ALIAS, {
      'spec.json': JSON.stringify(makeSpec({ specId: ALIAS, repository: 'hello-app' })),
      'preplan.json': '{}',
    });
    const files = await projectDraftFiles(draft, 'monolith', [{ alias: ALIAS }]);
    expect(Object.keys(files).filter((file) => file.endsWith('.json'))).toEqual([]);
  });

  it('refuses an alias that is not a slug before any path is read', async () => {
    const read = vi.spyOn(fs, 'readFile');
    await expect(projectDraftFiles(draft, 'monolith', [{ alias: '../x' }])).rejects.toThrow(RangeError);
    const files = read.mock.calls.map(([file]) => String(file));
    read.mockRestore();
    expect(files.some((file) => file.endsWith('spec.json') || file.endsWith('plan.md'))).toBe(false);
  });

  it('projects only the aliases it is given, and no spec.md without a spec.json', async () => {
    await writeAlias(ALIAS, { 'implementation-plan.md': '# plan\n' });
    await writeAlias('hello-app-other', { 'spec.json': JSON.stringify(makeSpec({ specId: 'hello-app-other', repository: 'hello-app' })) });
    const files = await projectDraftFiles(draft, 'monolith', [{ alias: ALIAS }]);
    expect(files[`docs/specify/${ALIAS}/spec.md`]).toBeUndefined();
    expect(files[`docs/specify/${ALIAS}/plan.md`]).toBe('# plan\n');
    expect(Object.keys(files).some((file) => file.includes('hello-app-other'))).toBe(false);
  });
});
